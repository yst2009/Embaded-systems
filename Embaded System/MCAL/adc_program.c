// ?????? ??? Registers
#define ADMIX  (*(volatile u8 *)0x7C)
#define ADCSRA (*(volatile u8 *)0x7A)
#define ADC    (*(volatile u16 *)0x78)
#define ADCH   (*(volatile u8 *)0x79)

// ??????? ???? ????? ?????? ???? ??? ?????? ?????
void (*ADC_CallBack)(void) = NULL;

void Vid_ADC_Init(u8 Copy_u8Ref, u8 Copy_u8Prescaler, u8 Copy_u8Resolution) {
    // 1. ????? ??? Reference
    ADMIX = (Copy_u8Ref << 6);
    
    // 2. ????? ??? Resolution
    if(Copy_u8Resolution == 1) CLR_BIT(ADMIX, 5);
    else SET_BIT(ADMIX, 5);

    // 3. ???? ??? Prescaler
    ADCSRA = Copy_u8Prescaler;
    
    // 4. ??? ??? ADC
    SET_BIT(ADCSRA, 7);
}

u16 U16_ADC_Read(u8 Copy_u8Channel) {
    ADMIX = (ADMIX & 0xE0) | Copy_u8Channel; // ????? ??????
    SET_BIT(ADCSRA, 6);                     // ???? ???????
    while (GET_BIT(ADCSRA, 6));             // ????? ??? ?? ????
    return ADC;                             // ??? ???????
}

u8 U8_ADC_Read(u8 Copy_u8Channel) {
    SET_BIT(ADMIX, 5);                      // ????? 8-bit
    ADMIX = (ADMIX & 0xE0) | Copy_u8Channel;
    SET_BIT(ADCSRA, 6);
    while (GET_BIT(ADCSRA, 6));
    return ADCH;                            // ??? ?????? ??????? ??
}

void ADC_VidEnableInterrupt(void) { SET_BIT(ADCSRA, 3); }
void ADC_VidDisableInterrupt(void) { CLR_BIT(ADCSRA, 3); }

void ADC_VidSetCallBack(void (*Copy_Ptr)(void)) {
    ADC_CallBack = Copy_Ptr;
}

// ??? ??? ADC ????? ??? ISR ?? ?? ???? ????? ?????? ??????
ISR(ADC_vect) {
    if (ADC_CallBack != NULL) ADC_CallBack();
}